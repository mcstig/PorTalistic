// Portalistic — Mac key codes to X keysyms, by key position (a US layout in the VM).

import Foundation

let keysyms: [UInt16: UInt32] = {
    var m: [UInt16: UInt32] = [:]
    let letters: [(UInt16, Character)] = [
        (0x00, "a"), (0x0B, "b"), (0x08, "c"), (0x02, "d"), (0x0E, "e"), (0x03, "f"), (0x05, "g"),
        (0x04, "h"), (0x22, "i"), (0x26, "j"), (0x28, "k"), (0x25, "l"), (0x2E, "m"), (0x2D, "n"),
        (0x1F, "o"), (0x23, "p"), (0x0C, "q"), (0x0F, "r"), (0x01, "s"), (0x11, "t"), (0x20, "u"),
        (0x09, "v"), (0x0D, "w"), (0x07, "x"), (0x10, "y"), (0x06, "z"),
        (0x1D, "0"), (0x12, "1"), (0x13, "2"), (0x14, "3"), (0x15, "4"), (0x17, "5"), (0x16, "6"),
        (0x1A, "7"), (0x1C, "8"), (0x19, "9"),
        (0x1B, "-"), (0x18, "="), (0x21, "["), (0x1E, "]"), (0x2A, "\\"), (0x29, ";"), (0x27, "'"),
        (0x32, "`"), (0x2B, ","), (0x2F, "."), (0x2C, "/"), (0x31, " "), (0x0A, "<"),
    ]
    for (code, ch) in letters { m[code] = UInt32(ch.unicodeScalars.first!.value) }
    let special: [(UInt16, UInt32)] = [
        (0x24, 0xff0d), (0x30, 0xff09), (0x33, 0xff08), (0x35, 0xff1b), (0x75, 0xffff),  // Return Tab BackSpace Escape Delete
        (0x73, 0xff50), (0x77, 0xff57), (0x74, 0xff55), (0x79, 0xff56), (0x72, 0xff63),  // Home End PgUp PgDn Insert(Help)
        (0x7B, 0xff51), (0x7E, 0xff52), (0x7C, 0xff53), (0x7D, 0xff54),                  // arrows
        (0x38, 0xffe1), (0x3C, 0xffe2), (0x3B, 0xffe3), (0x3E, 0xffe4),                  // Shift L/R, Control L/R
        (0x3A, 0xffe9), (0x3D, 0xffea), (0x39, 0xffe5),                                  // Alt (Option) L/R, Caps Lock
        (0x52, 0xffb0), (0x53, 0xffb1), (0x54, 0xffb2), (0x55, 0xffb3), (0x56, 0xffb4),  // keypad 0-4
        (0x57, 0xffb5), (0x58, 0xffb6), (0x59, 0xffb7), (0x5B, 0xffb8), (0x5C, 0xffb9),  // keypad 5-9
        (0x41, 0xffae), (0x43, 0xffaa), (0x45, 0xffab), (0x4B, 0xffaf), (0x4E, 0xffad),  // . * + / -
        (0x4C, 0xff8d), (0x51, 0xffbd), (0x47, 0xff7f),                                  // Enter = Clear(NumLock)
    ]
    for (code, ks) in special { m[code] = ks }
    let fkeys: [UInt16] = [0x7A, 0x78, 0x63, 0x76, 0x60, 0x61, 0x62, 0x64, 0x65, 0x6D, 0x67, 0x6F,
                           0x69, 0x6B, 0x71, 0x6A, 0x40, 0x4F, 0x50, 0x5A]                  // F1-F20
    for (i, code) in fkeys.enumerated() { m[code] = 0xffbe + UInt32(i) }
    return m
}()

// Modifier keys report through flagsChanged; these device-dependent bits say which one is down.
let modifierBits: [UInt16: UInt] = [
    0x38: 0x0002, 0x3C: 0x0004,   // left / right shift
    0x3B: 0x0001, 0x3E: 0x2000,   // left / right control
    0x3A: 0x0020, 0x3D: 0x0040,   // left / right option
]
